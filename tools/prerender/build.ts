export interface BuildOptions {
  root: string
  variant: Variant
  outDir: string
  htmlOnly?: boolean
  pagesFile?: string
  siteUrl?: string
  hoursJson?: string | null
  availabilityJson?: string | null
  /** DV-CATALOG: the GET /api/v1/public/catalog snapshot (undefined: SITE_CATALOG_JSON) */
  catalogJson?: string | null
  /** DV-PRICE-INTERIM: interim | catalog (undefined: SITE_PRICING, else site.config.json `pricing`) */
  pricing?: string | null
  booking?: string | null
  apiOrigin?: string | null
  now?: string | null
  log?: (line: string) => void
}

export interface BuildPage {
  slug: string
  route: string
  file: string
  hydrated: boolean
  bundle: string | null
  textBoundaries: number
  bytes: number
}

export interface BuildResult {
  variant: Variant
  outDir: string
  siteUrl: string
  pages: BuildPage[]
  files: Record<string, string>
  hoursSource: 'SITE_HOURS_JSON' | 'fallback'
  availabilitySource: SiteEnv['availabilitySource']
  catalogSource: SiteEnv['catalogSource']
  pricing: SiteEnv['pricing']
  booking: SiteEnv['booking']
  buildNow: string
  themeScript: { file: string; sha256: string } | null
  /** logical asset paths the build substituted a placeholder for (DV-LOGO) */
  placeholders: string[]
  warnings: string[]
}

const readJson = <T>(f: string): T => JSON.parse(fs.readFileSync(f, 'utf8')) as T

function loadHours(
  root: string,
  json: string | null | undefined,
  warn: (s: string) => void,
): { hours: PublicHours; source: BuildResult['hoursSource'] } {
  if (json) {
    try {
      return { hours: validatePublicHours(readSnapshot(json)), source: 'SITE_HOURS_JSON' }
    } catch (e) {
      warn(
        `SITE_HOURS_JSON is not a valid public hours payload (${e instanceof Error ? e.message : String(e)}); using src/data/hours.fallback.json`,
      )
    }
  } else warn('SITE_HOURS_JSON is not set; using src/data/hours.fallback.json (Mon-Sat hours, Sunday closed)')
  return {
    hours: validatePublicHours(readJson(path.join(root, 'src/data/hours.fallback.json'))),
    source: 'fallback',
  }
}

function clientEntry(
  slug: string,
  userProps: Record<string, unknown>,
  hours: { endpoint: string; timeoutMs: number; labels?: Record<string, string> } | null,
  freeze: { now: string } | null,
  imageSlotTag: string | null,
  timeZone: string | null,
  theme: { prop: string; values: string[] } | null,
): string {
  return (
    `// AUTO-GENERATED by tools/prerender/build.ts. DO NOT EDIT.\n` +
    `import { boot } from '@/client/boot'\n` +
    `import render, { meta } from '../${slug}.tsx'\n` +
    `import Logic from '../${slug}.logic.js'\n` +
    `boot({ meta, render, Logic, userProps: ${JSON.stringify(userProps)}, hours: ${JSON.stringify(hours)}, freeze: ${JSON.stringify(freeze)}, imageSlotTag: ${JSON.stringify(imageSlotTag)}, timeZone: ${JSON.stringify(timeZone)}, theme: ${JSON.stringify(theme)} })\n`
  )
}

export async function buildSite(o: BuildOptions): Promise<BuildResult> {
  const log = o.log ?? ((l: string) => console.log(l))
  const warnings: string[] = []
  const warn = (s: string) => {
    warnings.push(s)
    log(`warning: ${s}`)
  }
  const root = o.root
  const site = loadSiteConfig(root)
  const seo = loadSeo(root)
  const siteUrl = (o.siteUrl ?? process.env.SITE_URL ?? site.siteUrl).replace(/\/+$/, '')
  const { hours, source: hoursSource } = loadHours(
    root,
    o.hoursJson === undefined ? process.env.SITE_HOURS_JSON : o.hoursJson,
    warn,
  )
  const formatted: FormattedHours = formatHours(hours, site.hours.labels)
  const extracted = path.join(root, 'design', 'extracted')
  const generatedDir = path.join(root, '.generated', o.variant)
  const pinned = o.now ?? process.env.PRERENDER_NOW ?? null
  const now = pinned ?? process.env.SITE_BUILD_NOW ?? new Date().toISOString()
  if (Number.isNaN(new Date(now).getTime())) throw new Error(`the build instant is not a valid date: ${now}`)

  // 1. compile
  const all: CompileAll = compilePages({
    root,
    variant: o.variant,
    tplIds: o.variant === 'parity',
    allowComplexExpr: false,
    pagesFile: o.pagesFile,
  })
  fs.rmSync(generatedDir, { recursive: true, force: true })
  for (const p of all.pages)
    for (const [rel, data] of Object.entries(all.perPage[p.slug]!))
      writeFile(path.join(generatedDir, rel), data)
  for (const [rel, data] of Object.entries(all.shared)) writeFile(path.join(generatedDir, rel), data)
  log(`compiled ${all.pages.length} page(s) (variant ${o.variant}) -> ${path.relative(root, generatedDir)}`)

  // 1b. the site environment the bridge and the prerender share (only when a page is bridged)
  const bridged = all.pages.filter((p) => all.metas[p.slug]!.bridge)
  let env: SiteEnv | null = null
  if (bridged.length) {
    env = buildSiteEnv({
      site,
      hours,
      hoursSource,
      availabilityJson: o.availabilityJson === undefined ? process.env.SITE_AVAILABILITY_JSON : o.availabilityJson,
      catalogJson: o.catalogJson === undefined ? process.env.SITE_CATALOG_JSON : o.catalogJson,
      booking: o.booking === undefined ? process.env.SITE_BOOKING : o.booking,
      pricing: o.pricing === undefined ? process.env.SITE_PRICING : o.pricing,
      apiOrigin: o.apiOrigin === undefined ? process.env.SITE_API_ORIGIN : o.apiOrigin,
      now,
      warn,
    })
    writeSiteEnv(generatedDir, env)
    log(
      `site env: booking=${env.booking} api=${env.apiOrigin || '(same origin)'} hours=${env.hoursSource} availability=${env.availabilitySource} catalog=${env.catalogSource} pricing=${env.pricing} now=${env.buildNow}`,
    )
  }

  // 2. assets: fonts and images referenced by the pages (a missing image gets the placeholder PNG, DV-LOGO)
  const store = new AssetStore()
  const placeholders: string[] = []
  const assetsJson = fs.existsSync(path.join(extracted, 'assets.json'))
    ? readJson<{ files: Record<string, { kind: string; missing?: boolean }> }>(path.join(extracted, 'assets.json'))
    : { files: {} }
  const assetBytes = (logical: string): Buffer | null => {
    const rel = 'assets/' + logical.slice('/assets/'.length)
    const info = assetsJson.files[rel]
    if (!info) return null
    if (info.missing) {
      if (!placeholders.includes(logical)) {
        placeholders.push(logical)
        warn(`${logical} is not in design/original/loose yet; a ${PLACEHOLDER_SIZE}x${PLACEHOLDER_SIZE} transparent placeholder is built in its place (DEVIATIONS.md DV-LOGO)`)
      }
      return transparentPng(PLACEHOLDER_SIZE, PLACEHOLDER_SIZE)
    }
    if (info.kind === 'asset') return fs.readFileSync(path.join(extracted, rel))
    return null
  }
  for (const p of all.pages) {
    const m = all.metas[p.slug]!
    for (const f of m.fontFiles) store.add(f, fs.readFileSync(path.join(extracted, f.slice(1))))
    for (const a of m.assetPaths) {
      const rel = 'assets/' + a.slice('/assets/'.length)
      const info = assetsJson.files[rel]
      if (!info) throw new Error(`${p.slug}: ${a} is referenced but not in design/extracted/assets.json`)
      if (info.kind === 'frame')
        warn(`${p.slug}: nested page ${a} is referenced; frames are not emitted (decide once the design is read)`)
      else if (info.kind === 'script' || info.kind === 'import') {
        // helmet scripts are shipped only when the patch layer keeps them (none for this design: DV-IMG)
        if (m.helmetScripts.includes(a)) store.add(a, fs.readFileSync(path.join(extracted, rel)))
      } else {
        const bytes = assetBytes(a)
        if (bytes) store.add(a, bytes)
      }
    }
  }
  // icons from the logo (or the placeholder): favicon 32, apple-touch-icon 180, 512 for manifests/OG
  const icons: { rel: string; href: string; type?: string; sizes?: string }[] = []
  let iconUrl: string | null = null
  if (site.icon) {
    const rel = 'assets/' + site.icon.slice('/assets/'.length)
    const info = assetsJson.files[rel]
    if (!info) throw new Error(`site.config.json icon ${site.icon} is not an extracted asset`)
    const bytes = assetBytes(site.icon)!
    iconUrl = store.add(site.icon, bytes)
    const real = !info.missing && pngSize(bytes) !== null
    for (const [size, relName] of [
      [32, 'icon'],
      [180, 'apple-touch-icon'],
      [512, 'icon'],
    ] as const) {
      const png = real ? pngIcon(bytes, size) : transparentPng(size, size)
      const url = store.add(`/assets/icon-${size}.png`, png)
      icons.push({ rel: relName, href: url, type: 'image/png', sizes: `${size}x${size}` })
    }
  }

  // 3. prerender
  const rendered = new Map<string, Awaited<ReturnType<typeof renderPage>>>()
  const userPropsOf = new Map<string, Record<string, unknown>>()
  for (const p of all.pages) {
    const m = all.metas[p.slug]!
    const metaJson = readJson<PageMetaJson>(path.join(extracted, p.slug, 'meta.json'))
    const bindings = all.bindings[p.slug]!
    const userProps: Record<string, unknown> = { ...(metaJson.propDefaults ?? {}) }
    if (bindings.roots.includes('hours') && !m.bridge) userProps.hours = formatted
    userPropsOf.set(p.slug, userProps)
    const r = await renderPage({
      meta: m,
      generatedDir,
      userProps,
      shims: {
        siteUrl,
        storage: site.theme ? { [site.theme.storageKey]: site.theme.default } : {},
        width: typeof m.preview?.width === 'number' ? m.preview.width : 1480,
        height: typeof m.preview?.height === 'number' ? m.preview.height : 1000,
        // every page is rendered at the build instant; a bridged page's client pins its first render to it too
        now: m.bridge ? now : pinned,
        timeZone: hours.tz || 'America/New_York',
      },
    })
    if (r.errors.length) throw new Error(`${p.slug}: errors while prerendering:\n  ${r.errors.join('\n  ')}`)
    for (const w of r.warnings) warn(`${p.slug}: ${w}`)
    if (Object.keys(r.storageWrites).length)
      warn(
        `${p.slug}: the logic wrote to localStorage during the render: ${Object.keys(r.storageWrites).join(', ')}`,
      )
    rendered.set(p.slug, r)
    log(
      `prerendered ${p.slug}: ${r.html.length} chars, ${r.textBoundaries} text boundaries${m.hydrated ? ' (hydrated)' : ' (static)'}`,
    )
  }

  // 4. CSS (fonts/images rewritten, then hashed)
  const cssUrl = new Map<string, string>()
  for (const p of all.pages) {
    const css = store.rewrite(String(all.perPage[p.slug]![`${p.slug}.page.css`]), `${p.slug}.page.css`).text
    cssUrl.set(p.slug, store.add(`/assets/${p.slug}.css`, Buffer.from(css)))
  }

  // 5. scripts
  let themeScript: BuildResult['themeScript'] = null
  let themeUrl: string | null = null
  let hoursUrl: string | null = null
  const bundleUrl = new Map<string, string>()
  const needsHours = (slug: string) =>
    !all.metas[slug]!.bridge && /data-hours(-attr)?=/.test(String(all.perPage[slug]![`${slug}.tsx`]))
  if (!o.htmlOnly) {
    const clientDir = path.join(generatedDir, 'client')
    const entries: { name: string; file: string }[] = []
    const defines: Record<string, string> = {}
    const hydrated = all.pages.filter((p) => all.metas[p.slug]!.hydrated)
    const wantTheme = !!site.theme && hydrated.some((p) => all.metas[p.slug]!.usesThemeStorage)
    const wantHours = all.pages.some((p) => needsHours(p.slug))
    if (wantTheme) {
      entries.push({ name: 'theme', file: path.join(root, 'src/client/theme.entry.ts') })
      defines.__OASIS_THEME__ = JSON.stringify(site.theme)
    }
    if (wantHours) {
      entries.push({ name: 'hours', file: path.join(root, 'src/client/hours.entry.ts') })
      defines.__OASIS_HOURS__ = JSON.stringify({
        endpoint: site.hours.endpoint,
        timeoutMs: site.hours.timeoutMs,
        labels: site.hours.labels ?? {},
      })
    }
    for (const p of hydrated) {
      const m = all.metas[p.slug]!
      const file = path.join(clientDir, `${p.slug}.entry.tsx`)
      const hoursOpt = needsHours(p.slug)
        ? { endpoint: site.hours.endpoint, timeoutMs: site.hours.timeoutMs, labels: site.hours.labels ?? {} }
        : null
      // the design's theme prop gets the pre-hydration decision (DV-THEME) when the theme script is shipped for this page
      const themeOpt =
        wantTheme && m.usesThemeStorage && site.theme?.prop ? { prop: site.theme.prop, values: site.theme.values } : null
      writeFile(file, clientEntry(p.slug, userPropsOf.get(p.slug)!, hoursOpt, m.bridge ? { now } : null, site.imageSlots?.tag ?? null, m.bridge ? hours.tz || 'America/New_York' : null, themeOpt))
      entries.push({ name: `page-${p.slug}`, file })
    }
    const outputs = await bundleEntries({ root, generatedDir, variant: o.variant, entries, defines })
    for (const b of outputs) {
      const code = store.rewrite(b.code, `${b.name}.js`).text
      const url = store.add(`/assets/${b.name}.js`, Buffer.from(code))
      if (b.name === 'theme') {
        themeUrl = url
        themeScript = { file: url.slice(1), sha256: sha256(code) }
      } else if (b.name === 'hours') hoursUrl = url
      else bundleUrl.set(b.name.slice('page-'.length), url)
    }
    log(
      `bundled ${outputs.length} script(s): ${outputs.map((b) => `${b.name} ${(Buffer.byteLength(b.code) / 1024).toFixed(1)} KB`).join(', ') || 'none'}`,
    )
  }

  // 6. documents
  const files = new Map<string, Buffer>()
  const pages: BuildPage[] = []
  for (const p of all.pages) {
    const m = all.metas[p.slug]!
    const r = rendered.get(p.slug)!
    const pageSeo = seoFor(site, seo, p.slug, p.route, siteUrl)
    const ogImage = pageSeo.ogImage
      ? pageSeo.ogImage.startsWith('/')
        ? siteUrl + (store.url(pageSeo.ogImage) ?? pageSeo.ogImage)
        : pageSeo.ogImage
      : null
    const jsonLd = localBusinessJsonLd(site, siteUrl, hours, ogImage ?? (iconUrl ? siteUrl + iconUrl : null))
    const bodyHtml = store.rewrite(r.html, `${p.slug} markup`).text
    const fontPreloads = m.fontFiles.filter((f) => /-latin\.woff2$/.test(f)).map((f) => store.url(f)!)
    const bundle = bundleUrl.get(p.slug) ?? null
    const html = buildDocument({
      meta: m,
      lang: site.lang,
      siteName: site.name,
      seo: { ...pageSeo, title: pageSeo.title, ogImage },
      viewport: site.viewport,
      cssHref: cssUrl.get(p.slug)!,
      bundleHref: bundle,
      themeHref: m.hydrated && m.usesThemeStorage ? themeUrl : null,
      hoursHref: !m.hydrated && needsHours(p.slug) ? hoursUrl : null,
      fontPreloads,
      icons,
      jsonLd,
      bodyHtml,
      parityVals: o.variant === 'parity' && !m.hydrated ? r.vals : undefined,
      parityStatic: o.variant === 'parity' && !m.hydrated,
    })
    const file = routeFile(p.route)
    files.set(file, Buffer.from(html))
    pages.push({
      slug: p.slug,
      route: p.route,
      file,
      hydrated: m.hydrated,
      bundle,
      textBoundaries: r.textBoundaries,
      bytes: Buffer.byteLength(html),
    })
  }
  const indexPage = all.pages.find((p) => p.route === '/')
  files.set(
    '404.html',
    Buffer.from(
      notFoundDocument({
        lang: site.lang,
        siteName: site.name,
        cssHref: indexPage ? (cssUrl.get(indexPage.slug) ?? null) : null,
        homeHref: '/',
        // the 404 follows the device and the stored choice like the home page (DV-THEME)
        themeHref: themeUrl,
        logoHref: iconUrl,
        icons,
      }),
    ),
  )
  files.set('robots.txt', Buffer.from(robotsTxt(siteUrl)))
  files.set(
    'sitemap.xml',
    Buffer.from(
      sitemapXml(pages.map((p) => ({ loc: p.route === '/' ? `${siteUrl}/` : `${siteUrl}${p.route}` }))),
    ),
  )
  for (const e of store.emitted) files.set(e.file, e.bytes)

  const index = files.get('index.html')
  if (!index) throw new Error('no page has route "/" (design/pages.json): dist/index.html would be missing')
  if (!index.toString('utf8').includes(site.marker))
    throw new Error(`dist/index.html does not contain the marker text ${JSON.stringify(site.marker)}`)

  const fileHashes: Record<string, string> = {}
  for (const [f, b] of [...files].sort(([a], [b]) => (a < b ? -1 : 1))) fileHashes[f] = sha256(b)
  const manifest = {
    variant: o.variant,
    siteUrl,
    builtWith: 'tools/prerender/build.ts',
    buildNow: now,
    hoursSource,
    availabilitySource: env?.availabilitySource ?? 'none',
    catalogSource: env?.catalogSource ?? 'none',
    pricing: env?.pricing ?? 'interim',
    booking: env?.booking ?? 'sms',
    placeholders,
    pages,
    themeScript,
    files: fileHashes,
  }
  files.set('manifest.json', Buffer.from(JSON.stringify(manifest, null, 2) + '\n'))

  // 7. write atomically
  const outDir = path.resolve(root, o.outDir)
  const partial = outDir + '.partial'
  fs.rmSync(partial, { recursive: true, force: true })
  for (const [f, b] of files) writeFile(path.join(partial, f), b)
  fs.rmSync(outDir, { recursive: true, force: true })
  fs.renameSync(partial, outDir)
  log(
    `wrote ${files.size} files -> ${path.relative(root, outDir)}: ${pages.map((p) => `${p.file} (${p.hydrated ? 'hydrated' : 'static'})`).join(', ')}`,
  )
  return {
    variant: o.variant,
    outDir,
    siteUrl,
    pages,
    files: fileHashes,
    hoursSource,
    availabilitySource: env?.availabilitySource ?? 'none',
    catalogSource: env?.catalogSource ?? 'none',
    pricing: env?.pricing ?? 'interim',
    booking: env?.booking ?? 'sms',
    buildNow: now,
    themeScript,
    placeholders,
    warnings,
  }
}

function writeFile(file: string, data: string | Buffer): void {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, data)
}

async function main(argv: string[]): Promise<number> {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
  let variant: Variant = 'prod'
  let outDir = 'dist'
  let htmlOnly = false
  let pagesFile: string | undefined
  let now: string | undefined
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]!
    const eq = a.indexOf('=')
    const key = eq > 0 ? a.slice(0, eq) : a
    const val = () => (eq > 0 ? a.slice(eq + 1) : argv[++i]) ?? ''
    if (key === '--variant') {
      const v = val()
      if (v !== 'prod' && v !== 'parity') throw new CompileError(`--variant must be prod or parity, got ${v}`)
      variant = v
    } else if (key === '--out') outDir = val()
    else if (key === '--html-only') htmlOnly = true
    else if (key === '--pages') pagesFile = val()
    else if (key === '--now') now = val()
    else {
      console.error(`unknown argument ${a}`)
      return 2
    }
  }
  const r = await buildSite({ root, variant, outDir, htmlOnly, pagesFile, now })
  console.log(
    `build OK (${r.variant}): ${r.pages.length} page(s), booking ${r.booking}, hours from ${r.hoursSource}, availability ${r.availabilitySource}, catalog ${r.catalogSource}, pricing ${r.pricing}, ${r.placeholders.length} placeholder asset(s), ${r.warnings.length} warning(s)`,
  )
  return 0
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).then(
    (c) => process.exit(c),
    (e) => {
      console.error(
        e instanceof CompileError ? `build: ${e.message}` : e instanceof Error ? (e.stack ?? e.message) : e,
      )
      process.exit(e instanceof CompileError ? e.exit : 1)
    },
  )
}
